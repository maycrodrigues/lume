/*
 * Ficha de Anamnese Nutricional completa de cada paciente dos estudos de caso, coerente com a
 * queixa, a anamnese e a avaliação de cada uma. Chave = `CaseDefinition.key`.
 */

const question = (id: string) => {
  const found = allQuestions(NUTRITION).find((q) => q.id === id)
  if (!found) throw new Error(`Pergunta inexistente na ficha Nutricional: ${id}`)
  return found
}

const rowsOf = (id: string) => {
  const q = question(id)
  return q.type === 'grid' ? q.rows : []
}

/** Opção de escolha pelo começo do texto (ex.: "Tipo 4"), para não repetir os textos longos do modelo. */
const option = (id: string, prefix: string) => {
  const q = question(id)
  const found = q.type === 'choice' ? q.options.find((o) => o.startsWith(prefix)) : undefined
  if (!found) throw new Error(`Opção "${prefix}" inexistente em ${id}`)
  return found
}

const assertRows = (id: string, names: string[]) => {
  const rows = rowsOf(id)
  const unknown = names.filter((n) => !rows.includes(n))
  if (unknown.length) throw new Error(`Linhas inexistentes em ${id}: ${unknown.join(', ')}`)
}

/** Todas as linhas de sinais e sintomas pontuadas: 0 (ausente) salvo as informadas. */
function symptoms(id: string, scores: Record<string, number> = {}) {
  assertRows(id, Object.keys(scores))
  return Object.fromEntries(rowsOf(id).map((row) => [row, { score: String(scores[row] ?? 0) }]))
}

/** Todos os alimentos do questionário de frequência; os não citados são "Esporádico". */
function frequency(usual: Record<string, string>, notes: Record<string, string> = {}) {
  const id = 'nutrition_foodFrequency'
  assertRows(id, [...Object.keys(usual), ...Object.keys(notes)])
  return Object.fromEntries(
    rowsOf(id).map((food) => [food, { frequency: usual[food] ?? 'Esporádico', ...(notes[food] ? { notes: notes[food] } : {}) }]),
  )
}

/** Recordatório com as seis refeições: [horário, local, alimentos]. */
function recall(meals: Record<string, [string, string, string]>) {
  assertRows('nutrition_recall', Object.keys(meals))
  return Object.fromEntries(rowsOf('nutrition_recall').map((meal) => {
    const [time, place, foods] = meals[meal] ?? ['—', '—', 'Não faz esta refeição']
    return [meal, { time, place, foods }]
  }))
}

